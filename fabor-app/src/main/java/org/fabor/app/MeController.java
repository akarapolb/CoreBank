package org.fabor.app;

import java.time.LocalDate;
import java.util.List;
import java.util.Map;
import org.fabor.deposit.DepositService;
import org.fabor.ledger.application.LedgerStore;
import org.fabor.ledger.domain.AccountId;
import org.fabor.ledger.domain.BalanceType;
import org.fabor.ledger.domain.Direction;
import org.fabor.lending.Loan;
import org.fabor.lending.LoanRepo;
import org.fabor.lending.LoanService;
import org.fabor.onboarding.Party;
import org.fabor.onboarding.Ports;
import org.fabor.platform.money.Currency;
import org.fabor.platform.money.Money;
import org.fabor.platform.tenancy.TenantId;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

/**
 * The signed-in customer's own view, for the mobile app. The party always comes from the verified token (the
 * {@code party_id} claim), never from the request, so one customer cannot name another. Dates are the server's today.
 * A loan that belongs to someone else looks exactly like one that does not exist.
 */
@RestController
@RequestMapping("/api/v1/me")
class MeController {
    private final Ports.PartyRepo parties;
    private final DepositService deposits;
    private final LedgerStore ledgerStore;
    private final LoanRepo loanRepo;
    private final LoanService loans;
    private final TenantId tenant;
    private final Lifecycle lifecycle;

    MeController(Ports.PartyRepo parties, DepositService deposits, LedgerStore ledgerStore, LoanRepo loanRepo, LoanService loans,
                 TenantId tenant, Lifecycle lifecycle) {
        this.parties = parties;
        this.deposits = deposits;
        this.ledgerStore = ledgerStore;
        this.loanRepo = loanRepo;
        this.loans = loans;
        this.tenant = tenant;
        this.lifecycle = lifecycle;
    }

    record Profile(String partyId, String status, String depositAccountId) { }

    record Balance(long minor, String currency, LocalDate asOf) { }

    record Activity(String batchId, LocalDate date, String label, String direction, long minor) { }

    record NextDue(int number, LocalDate dueDate, long amountMinor, boolean overdue) { }

    /** {@code payableMinor} is what can be paid right now: billed items still unpaid. */
    record LoanSummary(String id, String status, long principalMinor, long outstandingMinor, int instalments, int paid,
                       long payableMinor, NextDue next) { }

    record Repayment(String reference, long amountMinor) { }

    private Party me(Actor actor) {
        return parties.find(actor.customerParty()).orElseThrow(() -> new SecurityException("No customer profile"));
    }

    private String account(Actor actor) {
        String a = me(actor).depositAccountId();
        if (a == null) {
            throw new IllegalStateException("Your account is not open yet");
        }
        return a;
    }

    @GetMapping
    Profile profile(Actor actor) {
        Party p = me(actor);
        return new Profile(p.id(), p.status().name(), p.depositAccountId());
    }

    @GetMapping("/balance")
    Balance balance(Actor actor) {
        LocalDate today = lifecycle.today();
        Money m = deposits.balance(account(actor), today);
        return new Balance(m.minor(), m.currency().code(), today);
    }

    @GetMapping("/activity")
    List<Activity> activity(Actor actor, @RequestParam(defaultValue = "30") int limit) {
        String acct = account(actor);
        int n = Math.max(1, Math.min(limit, 100));
        return ledgerStore.entries(tenant, new AccountId("dep:" + acct), BalanceType.SETTLED, Currency.THB, lifecycle.today(), n).stream()
                .map(e -> new Activity(e.batchId().value(), e.valueDate(), label(e.batchId().value()),
                        e.direction() == Direction.CREDIT ? "IN" : "OUT", e.amount().minor())).toList();
    }

    /** Plain-language description from the posting id (the ids are generated by the services, see their key schemes). */
    static String label(String batchId) {
        String id = batchId.contains(":") ? batchId.substring(batchId.indexOf(':') + 1) : batchId;
        if (id.startsWith("int-")) {
            return "Interest";
        }
        if (id.startsWith("wd-")) {
            return "Withdrawal";
        }
        if (id.startsWith("dep-")) {
            return "Deposit";
        }
        if (id.equals("disburse") || id.endsWith("disburse")) {
            return "Loan paid out";
        }
        if (id.contains("pay-") || id.contains("prepay-") || id.contains("recovery-")) {
            return "Loan payment";
        }
        return "Transaction";
    }

    @GetMapping("/loans")
    List<LoanSummary> myLoans(Actor actor) {
        String party = actor.customerParty();
        return loanRepo.idsByParty(party).stream().map(id -> loanRepo.find(id).orElseThrow()).map(l -> summary(l)).toList();
    }

    @PostMapping("/loans/{id}/repayments")
    LoanSummary repay(Actor actor, @PathVariable String id, @RequestBody Repayment r) {
        Loan loan = owned(actor, id);
        loans.repay(loan.id(), "app-" + r.reference(), Money.ofMinor(r.amountMinor(), Currency.of(loan.currency())), lifecycle.today());
        return summary(owned(actor, id));
    }

    private Loan owned(Actor actor, String id) {
        String party = actor.customerParty();
        return loanRepo.find(id).filter(l -> l.party().equals(party)).orElseThrow(() -> new IllegalArgumentException("No such loan " + id));
    }

    private LoanSummary summary(Loan l) {
        LocalDate today = lifecycle.today();
        long outstanding = l.instalments().stream().mapToLong(Loan.Instalment::principalOutstanding).sum();
        int paid = (int) l.instalments().stream().filter(Loan.Instalment::settled).count();
        NextDue next = null;
        for (Loan.Instalment i : l.instalments()) {
            if (!i.settled() && l.status() != Loan.Status.CLOSED && l.status() != Loan.Status.WRITTEN_OFF) {
                long due = i.billed() ? i.outstanding() : i.principalDue() + i.interestDue();
                next = new NextDue(i.number(), i.dueDate(), due, i.billed() && today.isAfter(i.dueDate()));
                break;
            }
        }
        long payable = l.instalments().stream().filter(Loan.Instalment::billed).mapToLong(Loan.Instalment::outstanding).sum();
        return new LoanSummary(l.id(), l.status().name(), l.principal(), outstanding, l.instalments().size(), paid, payable, next);
    }
}
