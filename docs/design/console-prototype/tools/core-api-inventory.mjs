// Writes docs/design/specs/core-api-inventory.md: every endpoint the Spring controllers in fabor-app expose today.
//
//   node docs/design/console-prototype/tools/core-api-inventory.mjs
//
// It reads the controllers as text (class-level @RequestMapping plus each @Get/@Post/@Put/@Patch/@DeleteMapping and the method
// name that follows), so it needs no build. Run it again after adding or changing an endpoint.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const appDir = join(here, "..", "..", "..", "..", "fabor-app", "src", "main", "java", "org", "fabor", "app");
const rows = [];
for (const f of readdirSync(appDir).filter((n) => n.endsWith("Controller.java")).sort()) {
  let base = "", pend = null;
  for (const ln of readFileSync(join(appDir, f), "utf8").split(/\r?\n/)) {
    let m = ln.match(/@RequestMapping\("([^"]*)"\)/);
    if (m && pend === null && !ln.includes("public")) { base = m[1]; continue; }
    m = ln.match(/@(Get|Post|Put|Patch|Delete)Mapping(.*)/);
    if (m) { const p = m[2].match(/"([^"]*)"/); pend = [m[1].toUpperCase(), base + (p ? p[1] : "")]; continue; }
    if (pend && !ln.trim().startsWith("@") && (/\bpublic\b/.test(ln) || /^\s*\w[\w<>, ?[\]]*\s+\w+\s*\(/.test(ln))) {
      const h = ln.match(/\b(\w+)\s*\(/);
      if (h) { rows.push([f.replace(".java", ""), pend[0], pend[1], h[1]]); pend = null; }
    }
  }
}
const out = ["# Core API inventory", "",
  "Generated by `docs/design/console-prototype/tools/core-api-inventory.mjs` from the Spring controllers in `fabor-app/src/main/java/org/fabor/app`. Run it again after adding or changing an endpoint. The specs in this folder map every console action to one of these endpoints, or mark it **New**.", "",
  `${rows.length} endpoints in ${new Set(rows.map((r) => r[0])).size} controllers.`, "", "| Controller | Method | Path | Handler |", "|---|---|---|---|",
  ...rows.map(([c, m, p, h]) => `| ${c} | ${m} | \`${p}\` | \`${h}\` |`)];
writeFileSync(join(here, "..", "..", "specs", "core-api-inventory.md"), out.join("\n") + "\n");
console.log(`core-api-inventory.md: ${rows.length} endpoints`);
